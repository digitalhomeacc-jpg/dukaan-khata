/// Marathi / English strings. Marathi is the default (for the shop owner);
/// a toggle in Settings / the app bar switches to English.
class Strings {
  final bool english;
  const Strings(this.english);

  String t(String key) {
    final e = _s[key];
    // a unit the shop made itself (ट्रिप, गाडी …) shows as typed
    if (e == null) return key.startsWith('unit_') ? key.substring(5) : key;
    return english ? e.$2 : e.$1;
  }

  String call(String key) => t(key);
}

