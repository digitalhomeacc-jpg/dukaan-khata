#!/usr/bin/env python3
"""Bundle the import-statement function into one file.  Usage: tool/bundle_import.py OUT.ts"""
import re, sys, pathlib
fn = pathlib.Path(__file__).resolve().parent.parent / "supabase/functions"
parsers = (fn / "ingest-email/parsers.ts").read_text()
statement = (fn / "import-statement/statement.ts").read_text()
index = (fn / "import-statement/index.ts").read_text()
local = re.compile(r'^import \{[^}]*\} from "\.\.?/[^"]+";\n', re.M)
statement, index = local.sub("", statement), local.sub("", index)
head = "".join(l + "\n" for l in index.splitlines() if l.startswith("import "))
body = "\n".join(l for l in index.splitlines() if not l.startswith("import "))
out = ("// Expense Tracker – import-statement (single file, generated by tool/bundle_import.py).\n\n"
       + head + "\n" + parsers + "\n" + statement + "\n" + body + "\n")
pathlib.Path(sys.argv[1]).write_text(out)
print("wrote", sys.argv[1])
