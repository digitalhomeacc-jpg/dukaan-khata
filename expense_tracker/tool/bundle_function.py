#!/usr/bin/env python3
"""Bundle the ingest-email function into one file (for the Supabase dashboard editor or the
Management API deploy).  Usage: tool/bundle_function.py OUT.ts"""
import re, sys, pathlib
src = pathlib.Path(__file__).resolve().parent.parent / "supabase/functions/ingest-email"
parsers = (src / "parsers.ts").read_text()
index = (src / "index.ts").read_text()
index = re.sub(r'^import \{[^}]*\} from "\./parsers\.ts";\n', "", index, flags=re.M)
assert "./parsers.ts" not in index
rest = index[index.index("import { createClient }"):]
first, body = rest.split("\n", 1)
parsers = re.sub(r"^// Bank alert email parser.*?\n\n", "", parsers, flags=re.S)
out = ("// Expense Tracker – ingest-email (single file, generated by tool/bundle_function.py).\n"
       "// Turn OFF \"Verify JWT\": the Gmail script sends its own per-user key.\n\n"
       + first + "\n\n" + parsers + "\n" + body)
pathlib.Path(sys.argv[1]).write_text(out)
print("wrote", sys.argv[1])
